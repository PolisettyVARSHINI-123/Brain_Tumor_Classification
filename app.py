import streamlit as st
import tensorflow as tf
import numpy as np
import json
from PIL import Image


# Page Configuration

st.set_page_config(
    page_title="Brain Tumor Classification",
    page_icon="🧠",
    layout="wide"
)

# Main Title

st.title("🧠 Brain Tumor Classification" )

st.write(
    "Upload an MRI brain image to classify its category "
    "using a CNN Deep Learning Model."
)

st.divider()
st.subheader("⚠️ Medical Disclaimer")

st.warning(
    "This application is developed for academic "
    "and educational purposes only. Predictions "
    "are generated by an experimental CNN model "
    "and must not be used for medical diagnosis "
    "or treatment decisions. Please consult a "
    "qualified healthcare professional."
)


# Tumor Categories

st.subheader("📋 Available Classification Categories")

col1, col2, col3, col4 = st.columns(4)

with col1:
    st.info("Glioma")

with col2:
    st.info("Meningioma")

with col3:
    st.info("No Tumor")

with col4:
    st.info("Pituitary")

model = tf.keras.models.load_model(
    r"dataset\brain_tumor_model.keras"
)

# Sidebar

st.sidebar.title("🧠 Project Information")

st.sidebar.write("Medical Image Classification")

st.sidebar.divider()

st.sidebar.subheader("Model Details")

st.sidebar.write("Algorithm: CNN")
st.sidebar.write("Framework: TensorFlow")
st.sidebar.write("Image Size: 224 × 224")
st.sidebar.write("Classes: 4")

st.sidebar.divider()

st.sidebar.caption(
    "Academic project - For educational purposes only."
)

with open(r"dataset\class_names.json", "r") as file:
    class_names = json.load(file)

uploaded_file = st.file_uploader(
        "Upload MRI Image",
        type=["jpg", "jpeg", "png"]
    )


if uploaded_file is not None:


    img = Image.open(uploaded_file).convert("RGB")


    st.image(
        img,
        caption="Uploaded MRI Image",
        use_container_width=True
    )
    img = img.resize((224, 224))
    img_array = np.array(img)
    img_array = img_array / 255.0
    img_array = np.expand_dims(img_array, axis=0)

    if st.button("Predict"):
        prediction = model.predict(img_array)
        result = np.argmax(prediction)
        st.success(
            "Predicted Class: " + class_names[result]
        )
        confidence = prediction[0][result] * 100

        st.write(
            "Confidence:", round(float(confidence), 2), "%"
        )
        # Prediction Probabilities
        st.subheader("Prediction Probabilities")

    for i, class_name in enumerate(class_names):
        probability = float(prediction[0][i]) * 100

        st.write(class_name, f"{probability:.2f}%")

        st.progress(float(prediction[0][i]))
else:
    st.info("Please upload an MRI image to continue.")
